import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { workspaceRoot } from './runtime.mjs';

const check = process.argv.includes('--check');
const registry = JSON.parse(await readFile(resolve(workspaceRoot, 'agents/registry.json'), 'utf8'));
const seen = new Set();
const MODELS = ['inherit', 'haiku', 'sonnet', 'opus', 'fable'];
const EFFORTS = ['low', 'medium', 'high', 'xhigh', 'max'];

// Claude Code frontmatter: per-role model, effort and removed tools keep each specialist's
// context and cost proportionate to its job. Codex roles inherit the Codex session model.
function claudeFrontmatter(role) {
  const model = role.model || 'inherit';
  if (!MODELS.includes(model)) throw new Error(`${role.name}: model must be one of ${MODELS.join(', ')}.`);
  if (role.effort && !EFFORTS.includes(role.effort)) throw new Error(`${role.name}: effort must be one of ${EFFORTS.join(', ')}.`);
  const removed = role.disallowedTools || [];
  if (!Array.isArray(removed) || !removed.every(t => /^[A-Za-z_][\w-]*$/.test(t))) {
    throw new Error(`${role.name}: disallowedTools must be a list of tool or MCP server names.`);
  }
  return [
    `name: ${role.name}`,
    `description: ${JSON.stringify(role.description)}`,
    `model: ${model}`,
    ...(role.effort ? [`effort: ${role.effort}`] : []),
    ...(removed.length ? [`disallowedTools: ${removed.join(', ')}`] : [])
  ].join('\n');
}
let stale = false;
for (const role of registry) {
  if (!/^qa-[a-z]+(?:-[a-z]+)*$/.test(role.name) || seen.has(role.name) || !role.description) throw new Error('Invalid or duplicate role definition.');
  seen.add(role.name);
  const contract = (await readFile(resolve(workspaceRoot, `agents/${role.name}.md`), 'utf8')).trim();
  const body = `Generated from agents/${role.name}.md. Edit the canonical file and run npm run agents:sync.\n\nFollow the root AGENTS.md. The main conversation coordinates; do not delegate further.\nUse the assigned workspace root and ticket paths. Honor exclusive write ownership.\n\n${contract}\n`;
  if (body.includes("'''")) throw new Error('Role instructions cannot contain a TOML literal multiline delimiter.');
  const files = [
    [`.claude/agents/${role.name}.md`, `---\n${claudeFrontmatter(role)}\n---\n\n${body}`],
    [`.codex/agents/${role.name}.toml`, `# Generated by npm run agents:sync.\nname = ${JSON.stringify(role.name)}\ndescription = ${JSON.stringify(role.description)}\ndeveloper_instructions = '''\n${body}'''\n`]
  ];
  for (const [name, content] of files) {
    const destination = resolve(workspaceRoot, name);
    if (check) {
      const current = await readFile(destination, 'utf8').catch(() => null);
      if (current !== content) { console.error(`Missing or stale: ${name}`); stale = true; }
    } else {
      await mkdir(resolve(destination, '..'), { recursive: true });
      await writeFile(destination, content);
    }
  }
}
if (stale) process.exitCode = 1;
else console.log(`${registry.length} roles: Claude Code and Codex adapters ${check ? 'are synchronized' : 'generated'}.`);
